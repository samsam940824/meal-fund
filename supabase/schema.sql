-- 家庭公費記帳：資料表與權限
-- 在 Supabase Dashboard → SQL Editor 貼上整份執行一次即可。
-- Amounts are whole New Taiwan Dollars stored as integer, which avoids floating point entirely.

create table public.meal_members (
  id          uuid primary key default gen_random_uuid(),
  name        text    not null check (char_length(name) between 1 and 20),
  monthly_due integer not null default 0 check (monthly_due between 0 and 10000000),
  active      boolean not null default true,
  -- Identity keeps the list in the order members were added, including ones added later in the app.
  sort_order  integer generated by default as identity,
  created_at  timestamptz not null default now()
);

-- 收入：家人交公費，或其他收入（例如開始使用時公帳原本就有的錢）
create table public.meal_contributions (
  id            uuid primary key default gen_random_uuid(),
  member_id     uuid    references public.meal_members (id),
  amount        integer not null check (amount between 1 and 10000000),
  received_date date    not null,
  -- 繳的是哪個月份的公費（可能提早或補繳），格式 YYYY-MM；非家人繳費時為 null
  for_month     text    check (for_month ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  description   text    not null default '' check (char_length(description) <= 100),
  created_at    timestamptz not null default now(),
  constraint dues_have_month check ((member_id is null) = (for_month is null)),
  constraint other_income_described check (member_id is not null or char_length(description) > 0)
);

-- 餐費支出：預設全由公費支付；公費現金不夠或有人先刷卡時，記下代墊人與代墊金額。
-- 代墊何時、由哪筆入帳歸還不存資料表，而是照日期順序重算（src/utils/ledgerCalc.ts settleAdvances），
-- 所以修改或刪除任何一筆都會自動重新對帳。
create table public.meal_expenses (
  id              uuid primary key default gen_random_uuid(),
  amount          integer not null check (amount between 1 and 10000000),
  spent_date      date    not null,
  description     text    not null check (char_length(description) between 1 and 100),
  advanced_by     uuid    references public.meal_members (id),
  advanced_amount integer not null default 0,
  created_at      timestamptz not null default now(),
  constraint advance_consistent check (
    (advanced_by is null and advanced_amount = 0)
    or (advanced_by is not null and advanced_amount between 1 and amount)
  )
);

-- 餘額、上月結餘、代墊歸還都在前端由全部紀錄算出（家庭公費資料量小），規則只有一份。

-- 權限：與其他 App（麻將）共用同一個 Supabase 專案，所以不能只看「有沒有登入」，
-- 只有全家共用帳號能讀寫；其他帳號或外流的 anon key 都讀不到。
-- 帳號 email 只寫在這個函式裡。repo 是公開的，所以這裡放佔位字串：
-- 在 SQL Editor 執行前，把 family@example.com 換成真正的全家共用帳號 email（忘了換的話誰都讀不到，不會外洩）。
-- 之後要換帳號，改 email 後只重新執行這個 create or replace function 即可。
create or replace function public.meal_is_family() returns boolean
  language sql stable
  as $$ select coalesce(auth.jwt() ->> 'email', '') = 'family@example.com' $$;

alter table public.meal_members       enable row level security;
alter table public.meal_contributions enable row level security;
alter table public.meal_expenses      enable row level security;

create policy family_only on public.meal_members       for all to authenticated using (public.meal_is_family()) with check (public.meal_is_family());
create policy family_only on public.meal_contributions for all to authenticated using (public.meal_is_family()) with check (public.meal_is_family());
create policy family_only on public.meal_expenses      for all to authenticated using (public.meal_is_family()) with check (public.meal_is_family());

revoke all on public.meal_members, public.meal_contributions, public.meal_expenses from anon;
grant select, insert, update, delete on public.meal_members, public.meal_contributions, public.meal_expenses to authenticated;
